export function MarkerAlphabetTypeface({
  text = "playful!",
  color = "#111111",
  scale = 1,
  seed = 1,
  className,
  style,
  ...props
}: MarkerAlphabetTypefaceProps) {
  const letters = text.toUpperCase().split("").map((char) => glyphs[char] ? char : "?");
  const gap = 2.3;
  const rawWidth = letters.reduce((sum, char) => sum + glyphs[char].width + gap, -gap);
  const viewWidth = Math.max(24, rawWidth + 8);
  let x = 4;

  return (
    <svg
      viewBox={`0 0 ${viewWidth} 20`}
      className={cx(className)}
      style={{ display: "block", width: "100%", height: "auto", ...style }}
      role="img"
      aria-label={text}
      {...props}
    >
      {letters.map((letter, index) => {
        const glyph = glyphs[letter];
        const jitter = (seeded(seed + index * 9.1) - 0.5) * 0.55;
        const rotate = (seeded(seed + index * 11.7) - 0.5) * 4;
        const stroke = letter === "!" ? 1.85 : 1.35;
        const node = (
          <g key={`${letter}-${index}`} transform={`translate(${x.toFixed(2)} ${(3 + jitter).toFixed(2)}) rotate(${rotate.toFixed(2)} ${glyph.width / 2} 8) scale(${scale})`}>
            <path d={glyph.d} fill="none" stroke={color} strokeWidth={stroke} strokeLinecap="round" strokeLinejoin="round" />
          </g>
        );
        x += glyph.width * scale + gap;
        return node;
      })}
    </svg>
  );
}
